int loadLevel(int n, uint8_t bricks[BRICK_ROWS][BRICK_COLUMNS])
{
	int breakable = 0;
	for (int row = 0; row < BRICK_ROWS; row++)
	{
		const char *line = levels[n % NUM_LEVELS][row];
		for (int col = 0; col < BRICK_COLUMNS; col++)
		{
			char c = line[col];
			uint8_t kind = BRICK_NONE;
			if (c >= '1' && c <= '8')
				kind = c - '0';
			else if (c == 'S')
				kind = BRICK_STEEL;
			else if (c == 'G')
				kind = BRICK_GOLD;
			bricks[row][col] = kind;
			if (kind != BRICK_NONE && kind != BRICK_GOLD)
				breakable++;
		}
	}
	return breakable;
}
